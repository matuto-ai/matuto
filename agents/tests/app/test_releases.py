"""The signed release list and release-file checks, through their own Python API."""

import hashlib
import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from matuto import releases


COMMIT = "b29c606e28a01b1bc8c1351026a0fa6e616bf6c4"
PAYLOAD = b"release"
SIZE = len(PAYLOAD)
SHA256 = hashlib.sha256(PAYLOAD).hexdigest()


def entry(**overrides):
    record = {"version": "2026.10.0", "commit": COMMIT, "size": SIZE, "sha256": SHA256,
              "notes": "The first release.", "prerequisites": ["openssh-client"],
              "changes_database": False, "withdrawn": False}
    record.update(overrides)
    return record


def document(number=1, releases=None):
    if releases is None:
        releases = [entry()]
    return json.dumps({"number": number, "releases": releases}).encode()


class KeyedTest(unittest.TestCase):
    """A throwaway key pair generated by `ssh-keygen` at test time; none is committed."""

    @classmethod
    def setUpClass(cls):
        cls.directory = tempfile.TemporaryDirectory(prefix="matuto-release-tests-")
        cls.trusted = Path(cls.directory.name) / "trusted"
        cls.other = Path(cls.directory.name) / "other"
        for key in (cls.trusted, cls.other):
            subprocess.run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", key.name,
                            "-f", str(key)], check=True, capture_output=True)

    @classmethod
    def tearDownClass(cls):
        cls.directory.cleanup()

    def public_key(self, key):
        return Path(f"{key}.pub").read_bytes()

    def sign(self, document_bytes, key=None, namespace=releases.SIGNATURE_NAMESPACE):
        key = self.trusted if key is None else key
        with tempfile.TemporaryDirectory(prefix="matuto-sign-") as directory:
            data = os.path.join(directory, "release-list.json")
            Path(data).write_bytes(document_bytes)
            subprocess.run(["ssh-keygen", "-Y", "sign", "-f", str(key), "-n", namespace, data],
                           check=True, capture_output=True)
            return Path(f"{data}.sig").read_bytes()

    def read(self, document_bytes, key=None, *, accepted_number=None):
        return releases.read_list(document_bytes, self.sign(document_bytes, key),
                                  self.public_key(self.trusted), accepted_number=accepted_number)

    def release(self, **overrides):
        data = document(releases=[entry(**overrides)])
        return self.read(data).release_list.releases[0]


class ListTest(KeyedTest):
    def test_a_list_signed_by_the_trusted_key_verifies_and_parses(self):
        data = document(number=4)
        reading = self.read(data)
        self.assertFalse(reading.stale)
        self.assertEqual(reading.release_list.number, 4)
        (release,) = reading.release_list.releases
        self.assertEqual(release.version, "2026.10.0")
        self.assertEqual(release.commit, COMMIT)
        self.assertEqual(release.size, SIZE)
        self.assertEqual(release.sha256, SHA256)
        self.assertEqual(release.notes, "The first release.")
        self.assertEqual(release.prerequisites, ("openssh-client",))
        self.assertFalse(release.changes_database)
        self.assertFalse(release.withdrawn)
        self.assertTrue(release.installable)

    def test_the_database_change_flag_parses(self):
        release = self.release(changes_database=True)
        self.assertTrue(release.changes_database)

    def test_a_semantic_version_parses(self):
        self.assertEqual(self.release(version="1.0.0").version, "1.0.0")

    def test_a_verified_list_is_readable_as_text_too(self):
        data = document().decode()
        reading = releases.read_list(data, self.sign(data.encode()), self.public_key(self.trusted))
        self.assertEqual(reading.release_list.number, 1)


class SignatureTest(KeyedTest):
    def test_a_list_signed_by_another_key_is_refused(self):
        data = document()
        with self.assertRaises(releases.ReleaseError):
            releases.read_list(data, self.sign(data, self.other), self.public_key(self.trusted))

    def test_a_tampered_list_is_refused(self):
        signature = self.sign(document(number=2))
        with self.assertRaises(releases.ReleaseError):
            releases.read_list(document(number=3), signature, self.public_key(self.trusted))

    def test_a_list_carrying_its_own_key_is_refused(self):
        payload = json.loads(document())
        payload["key"] = self.public_key(self.other).decode()
        data = json.dumps(payload).encode()
        with self.assertRaises(releases.ReleaseError):
            releases.read_list(data, self.sign(data, self.other), self.public_key(self.trusted))

    def test_a_list_signed_in_another_namespace_is_refused(self):
        data = document()
        with self.assertRaises(releases.ReleaseError):
            releases.read_list(data, self.sign(data, namespace="file"),
                               self.public_key(self.trusted))

    def test_a_trusted_key_that_is_not_a_public_key_is_refused(self):
        data = document()
        signature = self.sign(data)
        for key in (b"", b"not a key", b"-----BEGIN OPENSSH PRIVATE KEY-----", b"ssh-ed25519 !!!"):
            with self.subTest(key=key), self.assertRaises(releases.ReleaseError):
                releases.verify_signature(data, signature, key)

    def test_a_failing_signature_check_reports_the_reason(self):
        with self.assertRaises(releases.ReleaseError) as caught:
            releases.verify_signature(document(), b"not a signature", self.public_key(self.trusted))
        self.assertIn("does not verify", str(caught.exception))

    def test_a_missing_ssh_keygen_fails_with_that_reason(self):
        data = document()
        signature = self.sign(data)
        with tempfile.TemporaryDirectory() as empty:
            with mock.patch.dict(os.environ, {"PATH": empty}):
                with self.assertRaises(releases.ReleaseError) as caught:
                    releases.verify_signature(data, signature, self.public_key(self.trusted))
        self.assertIn("ssh-keygen", str(caught.exception))


class MalformedTest(KeyedTest):
    def test_a_list_missing_a_field_is_refused(self):
        for field in ("version", "commit", "size", "sha256", "notes", "prerequisites",
                      "changes_database", "withdrawn"):
            record = entry()
            del record[field]
            data = document(releases=[record])
            with self.subTest(field=field), self.assertRaises(releases.ReleaseError):
                self.read(data)
        for key in ("number", "releases"):
            payload = json.loads(document())
            del payload[key]
            data = json.dumps(payload).encode()
            with self.subTest(key=key), self.assertRaises(releases.ReleaseError):
                self.read(data)

    def test_a_field_named_twice_in_one_object_is_refused(self):
        # Python's json.loads keeps only the last of duplicate names, so a signed
        # list carrying two marks could be read as the attacker-chosen one.
        cases = {
            "duplicate withdrawn": document().replace(
                b'"withdrawn": false', b'"withdrawn": true, "withdrawn": false'),
            "duplicate list number": document(number=1).replace(
                b'"number": 1', b'"number": 1, "number": 9'),
            "duplicate version": document().replace(
                b'"version": "2026.10.0"', b'"version": "2026.10.0", "version": "2026.10.1"'),
        }
        for why, data in cases.items():
            with self.subTest(why=why), self.assertRaises(releases.ReleaseError) as caught:
                self.read(data, accepted_number=4)
            self.assertIn("twice", str(caught.exception))

    def test_an_otherwise_malformed_list_is_refused(self):
        cases = {
            "not JSON": b"{",
            "not an object": b"[]",
            "no releases": json.dumps({"number": 1, "releases": []}).encode(),
            "negative number": json.dumps({"number": -1, "releases": [entry()]}).encode(),
            "number not an integer": json.dumps({"number": "1", "releases": [entry()]}).encode(),
            "unknown list field": json.dumps({"number": 1, "releases": [entry()],
                                              "key": "ssh-ed25519 AAAA"}).encode(),
            "release not an object": json.dumps({"number": 1, "releases": ["2026.10.0"]}).encode(),
            "unknown release field": document(releases=[entry(extra=1)]),
            "bad version": document(releases=[entry(version="2026.1")]),
            "four parts": document(releases=[entry(version="1.0.0.0")]),
            "leading zero": document(releases=[entry(version="1.01.0")]),
            "bad commit": document(releases=[entry(commit="b29c606e")]),
            "negative size": document(releases=[entry(size=-1)]),
            "size not an integer": document(releases=[entry(size="7")]),
            "size is a boolean": document(releases=[entry(size=True)]),
            "bad SHA-256": document(releases=[entry(sha256="abc")]),
            "notes not text": document(releases=[entry(notes=5)]),
            "prerequisites not a list": document(releases=[entry(prerequisites="openssh-client")]),
            "an empty prerequisite": document(releases=[entry(prerequisites=[""])]),
            "database flag not a boolean": document(releases=[entry(changes_database="yes")]),
            "withdrawn not a boolean": document(releases=[entry(withdrawn=0)]),
            "duplicate version": document(releases=[entry(), entry()]),
        }
        for why, data in cases.items():
            with self.subTest(why=why), self.assertRaises(releases.ReleaseError) as caught:
                self.read(data)
            self.assertTrue(str(caught.exception), why)


class StaleTest(KeyedTest):
    def test_a_lower_numbered_list_is_stale_and_does_not_replace_what_is_known(self):
        data = document(number=3)
        reading = self.read(data, accepted_number=4)
        self.assertTrue(reading.stale)
        self.assertEqual(reading.release_list.number, 3)

    def test_an_equal_or_higher_numbered_list_is_not_stale(self):
        for number, accepted in ((4, 4), (5, 4)):
            with self.subTest(number=number, accepted=accepted):
                self.assertFalse(self.read(document(number=number), accepted_number=accepted).stale)

    def test_a_stale_list_never_makes_a_withdrawn_release_installable(self):
        # The accepted list at number 4 withdrew 2026.10.0; a replayed number-3
        # list calling it installable must be marked stale, so the caller keeps
        # the withdrawn state it already has.
        known = self.read(document(number=4, releases=[entry(withdrawn=True)]),
                          accepted_number=3)
        self.assertEqual(known.offered(), ())
        replayed = self.read(document(number=3, releases=[entry(withdrawn=False)]),
                             accepted_number=4)
        self.assertTrue(replayed.stale)
        self.assertEqual(replayed.offered(), ())


class WithdrawnTest(KeyedTest):
    def test_a_withdrawn_release_is_never_offered(self):
        data = document(number=2, releases=[entry(version="2026.10.0", withdrawn=True),
                                            entry(version="2026.10.1")])
        reading = self.read(data)
        self.assertEqual([release.version for release in reading.offered()], ["2026.10.1"])
        self.assertFalse(reading.release_list.releases[0].installable)
        self.assertTrue(reading.release_list.releases[1].installable)


class ReleaseFileTest(KeyedTest):
    def setUp(self):
        self.path = Path(self.directory.name) / "matuto-2026.10.0.release"
        self.path.write_bytes(PAYLOAD)

    def test_a_release_file_matching_its_entry_is_accepted(self):
        releases.check_release_file(self.path, self.release())

    def test_a_wrong_digest_is_refused(self):
        wrong = hashlib.sha256(b"other").hexdigest()
        with self.assertRaises(releases.ReleaseError) as caught:
            releases.check_release_file(self.path, self.release(sha256=wrong))
        self.assertIn("SHA-256", str(caught.exception))

    def test_a_wrong_size_is_refused(self):
        with self.assertRaises(releases.ReleaseError) as caught:
            releases.check_release_file(self.path, self.release(size=SIZE + 1))
        self.assertIn("bytes", str(caught.exception))

    def test_a_truncated_file_is_refused(self):
        self.path.write_bytes(PAYLOAD[:-1])
        with self.assertRaises(releases.ReleaseError) as caught:
            releases.check_release_file(self.path, self.release())
        self.assertIn("bytes", str(caught.exception))

    def test_an_unreadable_or_ordinary_file_is_refused(self):
        missing = Path(self.directory.name) / "missing.release"
        with self.assertRaises(releases.ReleaseError) as caught:
            releases.check_release_file(missing, self.release())
        self.assertIn("cannot be read", str(caught.exception))
        directory = Path(self.directory.name) / "a-directory"
        directory.mkdir()
        with self.assertRaises(releases.ReleaseError) as caught:
            releases.check_release_file(directory, self.release())
        self.assertIn("ordinary file", str(caught.exception))


